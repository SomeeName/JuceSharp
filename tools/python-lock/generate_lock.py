"""Regenerate the hash-locked package set the embedded interpreter installs.

    python -I tools/python-lock/generate_lock.py

Reads every pin from src/JuceSharp.StemSeparation/Runtime/PythonPackagePins.cs
(the one place a pin is written down), resolves them with `uv pip compile` for
CPython 3.11 on Windows x64 with binary wheels only, and keeps, per locked
package, ONLY the hashes of wheels that interpreter can install. The result is
src/JuceSharp.StemSeparation/PythonScripts/requirements-win_amd64-cp311.lock,
which PythonEnvManager installs with `pip install --require-hashes --no-deps`.

The hashes come from PyPI's JSON API (`digests.sha256` of each release file),
the same values pip checks. Needs network access and `uv` on PATH.
"""
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PINS_CS = REPO / "src" / "JuceSharp.StemSeparation" / "Runtime" / "PythonPackagePins.cs"
OUT = REPO / "src" / "JuceSharp.StemSeparation" / "PythonScripts" / "requirements-win_amd64-cp311.lock"

PY_TAGS = {"py3", "cp311", "py311", "py2.py3", "py3.py2"}
ABI_TAGS = {"none", "cp311", "abi3"}
PLATFORM_TAGS = {"any", "win_amd64"}


def read_pins() -> list[str]:
    text = PINS_CS.read_text(encoding="utf-8")
    pins = re.findall(r'public const string \w+ = "([^"]+)";', text)
    if not pins:
        sys.exit(f"No pins found in {PINS_CS}")
    return pins


def wheel_installable(filename: str) -> bool:
    if not filename.endswith(".whl"):
        return False
    parts = filename[:-4].split("-")
    if len(parts) < 5:
        return False
    py, abi, plat = parts[-3], parts[-2], parts[-1]
    if not any(t in PLATFORM_TAGS for t in plat.split(".")):
        return False
    if abi == "abi3":
        # Stable-ABI wheels are tagged with the OLDEST CPython they support.
        return any(re.fullmatch(r"cp3(\d+)", t) and int(t[3:]) <= 11 for t in py.split("."))
    return (any(t in PY_TAGS for t in py.split("."))
            and any(t in ABI_TAGS for t in abi.split(".")))


def pypi_hashes(name: str, version: str) -> list[tuple[str, str]]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json") as r:
        data = json.load(r)
    return sorted((u["digests"]["sha256"], u["filename"])
                  for u in data["urls"] if wheel_installable(u["filename"]))


def main() -> int:
    pins = read_pins()
    with tempfile.TemporaryDirectory() as tmp:
        req_in = Path(tmp) / "requirements.in"
        req_in.write_text("\n".join(pins) + "\n", encoding="utf-8")
        compiled = subprocess.run(
            ["uv", "pip", "compile", str(req_in), "--python-version", "3.11",
             "--python-platform", "x86_64-pc-windows-msvc", "--only-binary", ":all:",
             "--no-header", "--no-annotate", "--quiet"],
            check=True, capture_output=True, text=True).stdout

    locked = re.findall(r"^([A-Za-z0-9_.\-]+)==([^\s\\]+)", compiled, flags=re.M)
    if not locked:
        sys.exit("uv produced no pins")

    lines = [
        "# GENERATED by tools/python-lock/generate_lock.py. Do not edit by hand.",
        "# CPython 3.11, Windows x64, wheels only. Installed with",
        "# `pip install --require-hashes --no-deps --only-binary :all: -r <this file>`.",
        "# Pins: " + "; ".join(pins),
    ]
    for name, version in sorted(locked, key=lambda nv: nv[0].lower()):
        hashes = pypi_hashes(name, version)
        if not hashes:
            sys.exit(f"{name}=={version} has no wheel for cp311-win_amd64")
        lines.append(f"{name}=={version} \\")
        for i, (sha, filename) in enumerate(hashes):
            tail = " \\" if i < len(hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{sha}{tail}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(locked)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
