"""Regenerate the pinned Demucs weight table (DemucsWeightPins.g.cs).

    python -I tools/python-lock/generate_demucs_weights.py <path-to-demucs-wheel>

demucs >= 4.1 fetches its pretrained bags from the HuggingFace hub with no
revision and no hash, and falls back to dl.fbaipublicfiles.com with a 32-bit
checksum prefix and a full unpickle. JuceSharp therefore fetches the files
itself, through VerifiedDownload, from ONE pinned revision of each repository
with a full SHA-256, and hands the script a local directory.

Provenance, per file:
  * `<sig>.safetensors` -- the LFS SHA-256 HuggingFace reports for the pinned
    revision (the LFS object id IS the content SHA-256).
  * `<name>.yaml` -- downloaded at the pinned revision; its git blob id must
    equal the one the API reports, and its model list must equal the bag the
    demucs wheel itself ships in demucs/remote/<name>.yaml (the wheel is pinned
    by hash in the package lock). Only then is its SHA-256 recorded.
"""
import hashlib
import json
import sys
import urllib.request
import zipfile
from pathlib import Path

import yaml  # only for the cross-check against the wheel's bag list

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "src" / "JuceSharp.StemSeparation" / "Runtime" / "DemucsWeightPins.g.cs"
NAMESPACE = "adefossez"
# The bags the installed packages can run: the diffq-quantised ones need a
# package the lock does not install, so they are left out on purpose.
MODELS = {
    "htdemucs": "HTDemucs",
    "htdemucs_ft": "HTDemucs-ft",
    "htdemucs_6s": "HTDemucs-6s",
    "hdemucs_mmi": "Demucs-hdemucs_mmi",
    "mdx": "Demucs-mdx",
    "mdx_extra": "Demucs-mdx_extra",
}


def get_json(url):
    with urllib.request.urlopen(url) as r:
        return json.load(r)


def get_bytes(url):
    with urllib.request.urlopen(url) as r:
        return r.read()


def main() -> int:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    wheel = zipfile.ZipFile(sys.argv[1])
    rows = []
    for name, repo in MODELS.items():
        info = get_json(f"https://huggingface.co/api/models/{NAMESPACE}/{repo}/revision/main?blobs=true")
        rev = info["sha"]
        siblings = {s["rfilename"]: s for s in info["siblings"]}

        yaml_name = f"{name}.yaml"
        body = get_bytes(f"https://huggingface.co/{NAMESPACE}/{repo}/resolve/{rev}/{yaml_name}")
        blob = hashlib.sha1(b"blob %d\0" % len(body) + body).hexdigest()
        if blob != siblings[yaml_name]["blobId"]:
            sys.exit(f"{repo}/{yaml_name}: git blob id mismatch")
        bag = yaml.safe_load(body)
        shipped = yaml.safe_load(wheel.read(f"demucs/remote/{yaml_name}"))
        if bag["models"] != shipped["models"]:
            sys.exit(f"{repo}/{yaml_name}: bag {bag['models']} != wheel {shipped['models']}")

        files = [(yaml_name, hashlib.sha256(body).hexdigest(), len(body))]
        for sig in bag["models"]:
            s = siblings[f"{sig}.safetensors"]
            files.append((f"{sig}.safetensors", s["lfs"]["sha256"], s["size"]))
        rows.append((name, repo, rev, files))

    out = [
        "// <auto-generated>",
        "// GENERATED by tools/python-lock/generate_demucs_weights.py. Do not edit by hand.",
        "// </auto-generated>",
        "namespace JuceSharp.StemSeparation.Runtime;",
        "",
        "internal static partial class DemucsWeightPins",
        "{",
        "    private static readonly DemucsWeightBag[] Generated =",
        "    [",
    ]
    for name, repo, rev, files in rows:
        out.append(f'        new("{name}", "{NAMESPACE}/{repo}", "{rev}",')
        out.append("        [")
        for fn, sha, size in files:
            out.append(f'            new("{fn}", "{sha}", {size}),')
        out.append("        ]),")
    out += ["    ];", "}", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rows)} bags)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
