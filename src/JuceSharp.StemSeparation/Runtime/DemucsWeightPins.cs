namespace JuceSharp.StemSeparation.Runtime;

/// <summary>One file of a pinned Demucs bag.</summary>
internal sealed record DemucsWeightFile(string Name, string Sha256, long Bytes);

/// <summary>One pretrained Demucs bag: the HuggingFace repository, the commit
/// it is pinned to, and every file the separator reads from it.</summary>
internal sealed record DemucsWeightBag(string Model, string Repository, string Revision,
    IReadOnlyList<DemucsWeightFile> Files);

/// <summary>
/// Pinned Demucs weights, fetched through <see cref="VerifiedDownload"/> and
/// handed to <c>separate_track.py</c> as a local directory.
///
/// <para>
/// <b>Why demucs is not left to fetch its own.</b> demucs 4.1's
/// <c>pretrained.get_model</c> first asks the HuggingFace hub for the bag with
/// no revision and no hash, and builds whatever class the file's metadata names;
/// its fallback, <c>dl.fbaipublicfiles.com</c>, checks only the 8-hex-digit
/// (32-bit) SHA-256 prefix in the file name and then unpickles the file with
/// <c>weights_only=False</c>. Neither is a pin. Here every file is pinned to one
/// commit of its repository AND its full SHA-256, the hash is checked before the
/// file is renamed into place, and the script loads the directory offline.
/// </para>
/// <para>
/// The table is generated by <c>tools/python-lock/generate_demucs_weights.py</c>,
/// which cross-checks each bag's model list against the one the hash-locked
/// demucs wheel ships. The diffq-quantised bags are absent because the lock does
/// not install diffq.
/// </para>
/// </summary>
internal static partial class DemucsWeightPins
{
    /// <summary>Where the pinned files are fetched from. Internal so a test can
    /// point it at a loopback server.</summary>
    internal static Uri DefaultBaseUri { get; } = new("https://huggingface.co/");

    /// <summary>Every pinned bag.</summary>
    internal static IReadOnlyList<DemucsWeightBag> All => Generated;

    /// <summary>The bag for <paramref name="model"/>, or null when it is not pinned.</summary>
    internal static DemucsWeightBag? Find(string model) =>
        Generated.FirstOrDefault(b => string.Equals(b.Model, model, StringComparison.Ordinal));

    /// <summary>The URL of one file at the bag's pinned revision.</summary>
    internal static Uri FileUri(DemucsWeightBag bag, DemucsWeightFile file, Uri? baseUri = null) =>
        new(baseUri ?? DefaultBaseUri, $"{bag.Repository}/resolve/{bag.Revision}/{file.Name}");

    /// <summary>
    /// Makes <paramref name="directory"/> hold every file of
    /// <paramref name="bag"/>, each matching its pinned SHA-256 and size, and
    /// returns the directory. A file that is present but wrong is replaced; a
    /// download that does not match is refused and nothing is left in place.
    /// </summary>
    internal static async Task<string> EnsureAsync(
        DemucsWeightBag bag, string directory, Action<string>? log, CancellationToken ct,
        Uri? baseUri = null)
    {
        var dir = Path.GetFullPath(directory);
        Directory.CreateDirectory(dir);
        foreach (var file in bag.Files)
        {
            await VerifiedDownload.EnsureFileAsync(
                FileUri(bag, file, baseUri), Path.Combine(dir, file.Name), file.Sha256, file.Bytes,
                progress: null, log, ct, requireHash: true).ConfigureAwait(false);
        }
        return dir;
    }
}
