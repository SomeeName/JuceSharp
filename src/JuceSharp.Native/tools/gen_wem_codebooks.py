#!/usr/bin/env python3
"""Generate src/wem/wem_codebooks.h from ww2ogg's two packed codebook libraries.

Usage:
    python -I tools/gen_wem_codebooks.py <packed_codebooks.bin> <packed_codebooks_aoTuV_603.bin> <out.h>

The two .bin files are the libraries every ww2ogg port carries (hcs's ww2ogg
ships them beside the executable; the Ww2Ogg.Core NuGet package DotCharter used
before the native decoder embeds them as the resources
Ww2Ogg.Core.Internal.Codebooks.packed_codebooks{,_aoTuV_603}.bin). The header
records each file's SHA-256 so a regenerated table can be told apart from a
hand-edited one.
"""
import hashlib
import sys


def emit(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    return (f"inline constexpr std::size_t {name}Size = {len(data)};\n"
            f"inline constexpr unsigned char {name}[{len(data)}] = {{\n"
            + "\n".join(lines) + "\n};\n")


def main():
    default_path, aotuv_path, out_path = sys.argv[1:4]
    default = open(default_path, "rb").read()
    aotuv = open(aotuv_path, "rb").read()
    text = (
        "// GENERATED by tools/gen_wem_codebooks.py -- do not edit by hand.\n"
        "//\n"
        "// The two packed Vorbis codebook libraries Wwise strips out of a .wem's setup\n"
        "// header (it stores a 10-bit codebook ID instead of the codebook). Origin: the\n"
        "// ww2ogg project by Adam Gashlin (hcs), https://github.com/hcs64/ww2ogg,\n"
        "// distributed under its BSD-style licence (COPYING in that repo: Copyright (c)\n"
        "// 2002 Xiph.org Foundation, (c) 2009-2016 Adam Gashlin). The codebooks themselves\n"
        "// are the stock libvorbis 1.x and aoTuV beta 6.03 codebooks (Xiph BSD licence).\n"
        "// The bytes are the resources embedded in the Ww2Ogg.Core 1.0.0 NuGet package,\n"
        "// i.e. exactly what DotCharter's managed WEM path decoded with before this.\n"
        "//\n"
        f"//   packed_codebooks.bin            {len(default)} bytes  sha256 {hashlib.sha256(default).hexdigest()}\n"
        f"//   packed_codebooks_aoTuV_603.bin  {len(aotuv)} bytes  sha256 {hashlib.sha256(aotuv).hexdigest()}\n"
        "//\n"
        "// Layout (ww2ogg's codebook_library): the codebooks back to back, then a table\n"
        "// of little-endian uint32 offsets; the file's LAST four bytes are the offset of\n"
        "// that table, and the table's last entry is the end of the codebook data.\n"
        "#pragma once\n\n#include <cstddef>\n\nnamespace dcwem\n{\n"
        + emit("kPackedCodebooksDefault", default) + "\n"
        + emit("kPackedCodebooksAoTuV603", aotuv)
        + "} // namespace dcwem\n")
    with open(out_path, "w", newline="\n") as f:
        f.write(text)


if __name__ == "__main__":
    main()
